"""
bot/directions.py — каталог программ IT РОСТ и подбор по возрасту.

Вынесено отдельным модулем, а не зашито в хендлер: набор программ и
возрастные рамки меняются от учебного года к учебному году, и править
их должно быть можно в одном месте, не трогая логику диалога.

ИСТОЧНИК ДАННЫХ — рабочие программы (ДОП), утверждённые на базе МОУ
«СШ № 5 имени С.П. Королёва» г. Волжского. Возрастные рамки взяты
ОТТУДА, а не с сайта: на сайте программы сгруппированы в «ступени» по
классам для родителя, а в ДОП у каждой указан свой диапазон, и они
перекрываются (Scratch 7–10, робототехника 8–12). Если брать сетку с
сайта, ребёнок 8 лет увидел бы только Ступень I и не увидел бы
робототехнику, на которую его можно записать.

    Scratch-программирование        7–10 лет (1–4 кл.)   35 ч, 1 год
    Робототехника                   8–12 лет (2–6 кл.)   35 ч, 1 год
    Python: вводный курс            10–14 лет (4–8 кл.)  40 ч, полугодие
    Шахматы (начинающие)            7–14 лет (1–8 кл.)   72 ч, 1 год
    Шахматы (продолжающие)          8–15 лет, после начального курса
                                    или при наличии разряда

Во всех группах — до 8 человек.
"""

from typing import Dict, List

import settings

# code -> подпись кнопки. Коды короткие: они уезжают в payload
# callback-кнопки MAX, а он ограничен по длине.
DIRECTIONS: Dict[str, str] = {
    "scratch": "🐱 Scratch-программирование",
    "robo": "🤖 Робототехника",
    "python": "🐍 Python: вводный курс",
    "chess": "♟️ Шахматы (начинающие)",
    "chess2": "♟️ Шахматы (продолжающие)",
}

# Короткие пояснения — чтобы родитель понимал, что за кнопкой, до звонка.
DESCRIPTIONS: Dict[str, str] = {
    "scratch": "первые работающие программы: аркады, платформер, калькулятор",
    "robo": "сборка моделей на дистанционном управлении, робот-сортировщик, манипулятор",
    "python": "настоящий код: игры «Угадай число», «Крестики-нолики», квест, чат-бот",
    "chess": "правила, тактика и разбор партий с первого занятия",
    "chess2": "дебютный репертуар, разбор своих партий, подготовка к разряду",
}

# Диапазоны возраста из ДОП: code -> (от, до).
AGE_RANGES: Dict[str, tuple] = {
    "scratch": (7, 10),
    "robo": (8, 12),
    "python": (10, 14),
    "chess": (7, 14),
    "chess2": (8, 15),
}

# Программы, куда нельзя записаться «с нуля»: в группу для продолжающих
# зачисляют по итогам начального курса или при наличии разряда.
# Такие направления не показываются кнопкой новому посетителю — иначе
# родитель выберет её, а на звонке выяснится, что ребёнку туда рано.
#
# Из-за этого верхняя граница свободного набора — 14 лет
# (settings.MAX_AGE), хотя chess2 в ДОП идёт до 15: единственная
# программа для пятнадцатилетнего — та, куда его нельзя записать сразу.
REQUIRES_BACKGROUND = {"chess2"}


def directions_for_age(age: int) -> List[str]:
    """
    Коды программ, подходящих ребёнку указанного возраста.

    Порядок — как в каталоге DIRECTIONS, а не как получилось при
    переборе: иначе кнопки прыгали бы между показами.
    """
    return [
        code
        for code, (low, high) in AGE_RANGES.items()
        if low <= age <= high and code not in REQUIRES_BACKGROUND
    ]


def directions_for_ages(ages: List[int]) -> List[str]:
    """
    Объединение программ для нескольких детей, БЕЗ дублей и с
    сохранением порядка каталога.
    """
    matched = set()
    for age in ages:
        matched.update(directions_for_age(age))
    return [code for code in DIRECTIONS if code in matched]


def label(code: str) -> str:
    return DIRECTIONS.get(code, code)


def describe(code: str) -> str:
    text = DESCRIPTIONS.get(code)
    return f"{label(code)} — {text}" if text else label(code)


# Разумный потолок числа детей в одной заявке. Больше — почти наверняка
# человек прислал не возрасты, а что-то другое (год, номер, дату).
MAX_CHILDREN = 6


def parse_ages(text: str) -> List[int]:
    """
    Возраст детей из свободного текста: «9», «8 11», «8, 11», «8 и 11 лет».

    Повторы НЕ убираются: «9 9» — это двойняшки, и программу им нужно
    выбирать по отдельности.

    Числа вне разумных рамок (0 или больше 100) отбрасываются: это почти
    наверняка год рождения или номер телефона, а не возраст.
    """
    digits: List[int] = []
    current = ""
    for char in (text or ""):
        if char.isdigit():
            current += char
        else:
            if current:
                digits.append(int(current))
                current = ""
    if current:
        digits.append(int(current))

    result = [value for value in digits if 0 < value <= 100]
    return result[:MAX_CHILDREN]
